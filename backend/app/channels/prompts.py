def get_prompt_text(prompt_key: str, language: str = "hi", **kwargs: Any) -> str:
    """Return the native-language text for a given prompt key with optional formatting."""
    prompts_for_key = PROMPTS.get(prompt_key, {})
    template = (
        prompts_for_key.get(language)
        or prompts_for_key.get("hi")
        or prompts_for_key.get("en")
        or prompt_key
    )
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template


def spell_docket_digits(docket_ref: str, language: str = "hi") -> list[str]:
    """Break an alphanumeric tracking token (e.g. JS-7K4M-92QX) into clean readable words

    spelled character-by-character in the caller's native language.
    """
    lang_digits = DIGIT_WORDS.get(language, DIGIT_WORDS["hi"])
    result: list[str] = []
    clean_ref = (docket_ref or "").replace("anon_", "")
    for char in clean_ref:
        if char.isdigit() and char in lang_digits:
            result.append(lang_digits[char])
        elif char.isalpha():
            result.append(char.upper())
        elif char in "-_ ":
            result.append("dash" if language == "en" else "-")
        else:
            result.append(char)
    return result
